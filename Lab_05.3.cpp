double f(const double x)
{
    // Перевірка області збіжності, вказаної на малюнку (0 < x <= 2)
    if (x <= 0 || x > 2) {
        return 0; 
    }

    double s = 0.0;
    double term = x - 1.0; // Перший додаток при n = 0: (x - 1)

    // Обчислюємо перші 10 членів ряду для досягнення хорошої точності
    for (int n = 0; n < 10; n++)
    {
        s += term / (n + 1.0);
        term *= -(x - 1.0); // Наступний степінь із протилежним знаком
    }
    
    return s;
}
